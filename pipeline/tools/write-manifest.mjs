// Prepares <run>/video for rendering: copies the Remotion template (never over scene files the generator wrote),
// writes src/brand.ts from scenario.style, writes src/scenes/index.ts from scenario.json + prompts.json, and
// bundles the brand fonts into public/fonts.
//   node pipeline/tools/write-manifest.mjs <run dir>
import { cpSync, existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { TRANSITION_FRAMES, load } from "../schema.mjs";
import { TEMPLATE, ensureDir, runPaths, sceneFrames, sh } from "./common.mjs";

const fontFile = (family) => `${family.replace(/[^A-Za-z0-9]/g, "")}-latin.woff2`;

/** Download the latin subset of a Google font (variable weight when Google has it). Uses curl so proxies work. */
function fetchFont(family, dest) {
  const ua = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/141 Safari/537.36";
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, "+")}:wght@400;700&display=swap`;
  const css = sh("curl", ["-sSfL", "-A", ua, url], { capture: true });
  const block = css.split("/* latin */")[1] || css;
  const m = block.match(/url\((https:[^)]+\.woff2)\)/);
  if (!m) throw new Error(`Google Fonts has no woff2 for "${family}"`);
  sh("curl", ["-sSfL", "-o", dest, m[1]], { capture: true });
}

export function writeManifest(run) {
  const p = runPaths(run);
  const scenario = load(p.dir, "scenario.json");
  const prompts = load(p.dir, "prompts.json");
  if (scenario.engine !== "remotion") throw new Error("write-manifest is for the remotion engine only");

  // Template files, without clobbering scenes the generator already wrote.
  cpSync(TEMPLATE, p.video, {
    recursive: true,
    filter: (src) => !(src.includes(`${join("src", "scenes")}`) && existsSync(src.replace(TEMPLATE, p.video))),
  });
  ensureDir(join(p.video, "src", "scenes"));

  const st = scenario.style;
  const fontsDir = ensureDir(join(p.video, "public", "fonts"));
  for (const fam of [st.font_display, st.font_mono]) {
    const f = join(fontsDir, fontFile(fam));
    if (!existsSync(f)) {
      console.log(`fetching font ${fam}`);
      fetchFont(fam, f);
    }
  }
  writeFileSync(
    join(p.video, "src", "brand.ts"),
    `// GENERATED by pipeline/tools/write-manifest.mjs from scenario.json. Edit the scenario, not this file.
export const BRAND = ${JSON.stringify(
      {
        aspect: scenario.aspect,
        background: st.background,
        ink: st.ink,
        accent: st.accent,
        warn: st.warn ?? st.accent,
        danger: st.danger ?? st.ink,
        fontDisplay: st.font_display,
        fontDisplayFile: fontFile(st.font_display),
        fontMono: st.font_mono,
        fontMonoFile: fontFile(st.font_mono),
      },
      null,
      2,
    )} as const;
`,
  );

  // Scene list: every scenario scene needs a component in prompts.json and a file in src/scenes.
  const specs = new Map(prompts.remotion.scenes.map((s) => [s.id, s]));
  const { total, frames } = sceneFrames(scenario);
  const missing = [];
  const rows = scenario.scenes.map((s, i) => {
    const spec = specs.get(s.id);
    if (!spec) throw new Error(`prompts.json has no remotion scene for "${s.id}"`);
    if (!existsSync(join(p.video, "src", "scenes", `${spec.component}.tsx`))) missing.push(`src/scenes/${spec.component}.tsx`);
    const next = scenario.scenes[i + 1];
    const overlap = next && next.transition_in !== "none" ? TRANSITION_FRAMES : 0;
    if (frames[i] < TRANSITION_FRAMES * 2) throw new Error(`scene "${s.id}" is too short for transitions (${frames[i]} frames)`);
    return { id: s.id, component: spec.component, sequenceFrames: frames[i] + overlap, transition: i === 0 ? "none" : s.transition_in };
  });
  const audio = Object.fromEntries(["voiceover", "music", "sfx"].map((k) => [k, existsSync(join(p.publicAudio, `${k}.mp3`))]));
  const imports = [...new Set(rows.map((r) => r.component))].map((c) => `import { ${c} } from "./${c}";`).join("\n");
  writeFileSync(
    join(p.video, "src", "scenes", "index.ts"),
    `// GENERATED by pipeline/tools/write-manifest.mjs from scenario.json + prompts.json. Do not edit.
// A scene's sequence is longer than its share of the video by the transition that overlaps the next scene,
// so the scene lengths still add up to TOTAL_FRAMES.
import type React from "react";
${imports}

export const TRANSITION_FRAMES = ${TRANSITION_FRAMES};
export const TOTAL_FRAMES = ${total};
export const SCENES: { id: string; Component: React.FC; sequenceFrames: number; transition: string }[] = [
${rows.map((r) => `  { id: ${JSON.stringify(r.id)}, Component: ${r.component}, sequenceFrames: ${r.sequenceFrames}, transition: ${JSON.stringify(r.transition)} },`).join("\n")}
];
export const AUDIO = ${JSON.stringify(audio)};
`,
  );
  const present = readdirSync(join(p.video, "src", "scenes")).filter((f) => f.endsWith(".tsx"));
  return { total, rows, audio, missing, present };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const r = writeManifest(process.argv[2]);
  console.log(`manifest: ${r.rows.length} scenes, ${r.total} frames, audio ${JSON.stringify(r.audio)}`);
  if (r.missing.length) {
    console.error(`missing scene components:\n  ${r.missing.join("\n  ")}`);
    process.exit(1);
  }
}
